let _i18nLang = "ko";

function t(key, params) {
  const table = I18N_TRANSLATIONS[_i18nLang] || I18N_TRANSLATIONS.ko;
  let s = table[key];
  if (s == null) s = I18N_TRANSLATIONS.ko[key] || key; // fallback to ko, then key
  if (params) {
    for (const k of Object.keys(params)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(params[k]));
    }
  }
  return s;
}

function i18nSetLang(lang) {
  if (!I18N_TRANSLATIONS[lang]) lang = "ko";
  _i18nLang = lang;
  applyTranslations();
  document.documentElement.lang = lang;
}

function i18nGetLang() {
  return _i18nLang;
}

// data-i18n / data-i18n-html / data-i18n-attr 속성을 가진 모든 요소에 번역 적용.
function applyTranslations() {
  document.title = t("page.title");
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    // 형식: "placeholder:key" 또는 "title:key,placeholder:key2" (콤마 구분)
    const pairs = el.dataset.i18nAttr.split(",");
    for (const pair of pairs) {
      const [attr, key] = pair.split(":").map((s) => s.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    }
  });
}
